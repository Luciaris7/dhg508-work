class Refused(Exception):
    """An action the world will not allow.  The message is shown, not hidden."""


class Game:
    def __init__(self, kb=None):
        self.kb = kb or {}
        self.reset()

    # ---------------------------------------------------------------- set-up
    def reset(self):
        self.t = START
        self.place = "bridge"
        self.rockets = 0                 # fired so far (the world's count)
        self.seen_rockets = 0            # what the player has actually seen
        self.light_visible = False
        self.master_reported = False     # Stone -> master, 1.10
        self.sent_below = False          # Stone -> apprentice, 2.0
        self.reported_to_master = False  # the player has been down with it
        self.gear_open = False
        self.shown = []                  # narration, newest last
        self.log = []                    # the scrap log: [{"time","text"}]
        self.claims = []                 # numbers the player asserted
        self.beats_done = set()
        self.turns = 0
        self.calls = 0
        self.spend = {"calls": 0, "usd": 0.0, "in": 0, "out": 0}
        self.refusals = 0
        self.divergence = None
        self.ended = False
        self.stone = {"say": "", "zh": "", "act": "", "why": "", "source": ""}
        self._say("世界", "你是 James Gibson，Californian 号的中班学徒，二十岁。"
                         "现在是 4 月 15 日零点十五分，你的值班从午夜开始，到四点。"
                         "船从十点二十分起停在冰区里，主机停着，船头被掉成东北偏东。"
                         "二副 Stone 在桥楼上。你手上有一本值班簿。", kind="open")

    # ---------------------------------------------------------------- output
    def _say(self, who, text, kind="narrate", zh=None):
        self.shown.append({
            "time": clock_text(self.t),
            "who": who,
            "text": text,
            "zh": zh,
            "kind": kind,
        })
        del self.shown[:-60]

    def place_objects(self):
        return PLACES[self.place]["objects"]

    def visible(self):
        """What the player can see from here, in plain sentences."""
        lines = []
        if self.place == "chart_room":
            lines.append("海图室的门在你身后合上。船长在椅子上。")
            return lines
        if self.light_visible:
            anchor = ("右舷正横，四到七英里" if self.place == "bridge"
                      else "右舷前方，低而远")
            lines.append("来船的灯火：%s。" % anchor)
        if self.rockets:
            lines.append("到目前为止，你亲眼看见 %d 枚白色火箭。" % self.seen_rockets)
        lines.append("冰：船四周是田冰，冰面平到能反光。")
        return lines

    # ---------------------------------------------------------------- clock
    def advance(self, minutes):
        target = self.t + minutes
        for at, kind, text in BEATS:
            if self.t < at <= target and at not in self.beats_done:
                self.beats_done.add(at)
                self.t = at
                self._beat(kind, text)
        self.t = min(target, END)
        if self.t >= END and not self.ended:
            self._end()

    def _beat(self, kind, text):
        if kind == "light":
            self.light_visible = True
            self._say("世界", text)
        elif kind == "gear":
            self.gear_open = True
            self._say("Stone", "Gibson — get that patent-log gear ready below.",
                      zh="「Gibson——下去把备用的专利计程仪准备好。」", kind="stone")
        elif kind == "rocket":
            self.rockets += 1
            if self.place != "chart_room":
                self.seen_rockets += 1
                self._say("世界", text)
            if self.rockets == 5:
                self._say("世界", "五枚了。从第一枚算起，不到二十分钟。")
        elif kind == "report":
            self.master_reported = True
            self._say("世界", "传声筒的盖子掀开。Stone 俯身对着铜管说话，声音压得很低。"
                             "你听见他这边的话，也听见他重复对方的话。")
            self._say("世界", "……「Are they company's signals?」……「I do not know, but they "
                             "appear to me to be white rockets.」……「Go on Morsing.」……"
                             "「…send the apprentice down to me with it.」",
                      zh="「是公司的信号吗？」「我不知道，但在我看来是白色火箭。」"
                         "「继续用莫尔斯灯呼叫。」「……有什么消息，叫学徒下来告诉我。」")
            self.stone = {"say": "He says go on Morsing. Anything I get, you take down to him.",
                          "zh": "他说继续用莫尔斯灯叫。有什么消息，你下去告诉他。",
                          "act": "report_master", "why": "（记录在案：1.10 的传声筒通话）",
                          "source": "record"}
        elif kind == "queer":
            self._say("Stone", "Look at her now — she looks very queer out of water, her lights look queer.",
                      zh="「你看她现在——出了水，样子很怪，灯也不对。」", kind="stone")
        elif kind == "send":
            self.sent_below = True
            self._say("Stone", "Go down to the master. Wake him. Tell him altogether we have seen "
                              "eight of these white lights like white rockets; she is disappearing "
                              "in the south-west; we have called her up repeatedly and got no "
                              "information whatsoever.",
                      zh="「下去见船长，叫醒他。告诉他我们一共看见八枚白色的、像火箭一样的灯；"
                         "那条船正往西南方消失；我们反复用莫尔斯灯呼叫，什么也没得到。」", kind="stone")
        elif kind == "disappear":
            self._say("世界", text)
        elif kind == "end":
            pass

    def _end(self):
        self.ended = True
        self._say("世界", "两点二十分。你什么也不知道。三十英里内外，"
                         "另一条船在这几分钟里沉没了。", kind="end")

    # ---------------------------------------------------------------- actions
    def act(self, action):
        """Validate one action, apply it, return the events it produced."""
        if self.ended:
            raise Refused("值班已经结束。按「重来」重新开始。")
        kind = (action.get("action") or "").strip()
        self.turns += 1
        before = len(self.shown)

        if kind == "look":
            self._look(action.get("target") or "")
            self._tick(COST["look"])
        elif kind == "say":
            text = (action.get("text") or "").strip()
            if not text:
                raise Refused("你没有说话。要说什么，写在框里。")
            if self.place != "bridge":
                raise Refused("Stone 在桥楼上。你在这里说话，他听不见。要找他，先回桥楼。")
            self._say("你", text, kind="player")
            claim = rocket_claim(text)
            if claim is not None:
                self.claims.append({"time": watch_time(self.t), "said": claim,
                                    "true": self.rockets})
                if claim != self.rockets:
                    self._say("世界", "（到这一刻，海面上响起过 %d 枚火箭。你说的是 %d 枚。"
                                     "谁数错了，值班簿会记得。）" % (self.rockets, claim))
            reply = self._needs_stone(text)     # the exchange happens at this minute
            self._tick(COST["say"])             # and then the clock moves
            return {"events": self.shown[before:], "stone": reply}
        elif kind == "morse":
            self._morse(action.get("text") or "")
            self._tick(COST["morse"])
        elif kind == "walk":
            self._walk(action.get("to") or "")
            self._tick(COST["walk"])
        elif kind == "write":
            self._write(action.get("text") or "")
            self._tick(COST["write"])
        elif kind == "cross":
            self._cross(action.get("line"))
            self._tick(COST["cross"])
        elif kind == "wait":
            self._say("世界", "你站着等。冰山不响，灯也不动。")
            self._tick(COST["wait"])
        elif kind == "report":
            self._report_to_master()
            self._tick(COST["report"])
        else:
            raise Refused("不认得的动作：%r。可用的是 look / say / morse / walk / write / cross / wait / report。"
                          % kind)
        return {"events": self.shown[before:], "stone": None}

    def _tick(self, minutes):
        self.advance(minutes)

    def _look(self, target):
        target = target.strip().lower()
        objects = self.place_objects()
        if target not in objects:
            raise Refused("这里看不到「%s」。能看的是：%s。"
                          % (target or "什么", "、".join(sorted(objects))))
        self._say("世界", objects[target])
        if target == "light" and self.light_visible and self.place != "chart_room":
            self._say("世界", "你数了一下：桅灯是白的，侧灯是红的。这不够判断她是谁。")
        if target == "log":
            self._say("世界", "值班簿上一共 %d 行，写满就再也写不下了（上限 %d 行）。"
                      % (len(self.log), MAX_LOG))

    def _morse(self, text):
        if self.place != "bridge":
            raise Refused("莫尔斯灯在桥楼顶上。你得先回到桥楼。")
        self._say("世界", "你按下键盘，灯一闪一闪地打过去。对方的桅灯还在闪，但没有回音。")
        if self.rockets:
            self._say("世界", "船上的灯没有回答。这是第几次呼叫，你已经记不清了。")

    def _walk(self, to):
        to = to.strip().lower()
        if to not in PLACES:
            raise Refused("没有这个去处。能去的是：%s。" % "、".join(PLACES))
        if to == self.place:
            raise Refused("你已经在这里。")
        if to == "chart_room" and not self.sent_below:
            raise Refused("海图室的门关着。你是中班的值班学徒，没有理由离开桥楼，"
                          "也没有理由去推那扇门——除非二副叫你去。")
        if self.place == "chart_room" and to != "chart_room":
            pass
        self.place = to
        self._say("世界", "你到了%s。" % PLACES[to]["name"])
        if to == "chart_room":
            self._say("世界", "门在身后合上。船长在椅子上，眼睛睁着，或者闭着。"
                             "桌上摊着海图。你得说清你来干什么。")
        if to == "foredeck":
            self._say("世界", "甲板上更冷。冰就在舷外，一层压着一层，望不到头。")

    def _write(self, text):
        text = text.strip()
        if not text:
            raise Refused("空的一行不值得写。")
        if len(text) > 160:
            raise Refused("值班簿一行写不下这么长（上限 160 字）。")
        if len(self.log) >= MAX_LOG:
            raise Refused("值班簿满了（%d 行）。你得先划掉一行（cross），才写得上新的。"
                          % MAX_LOG)
        self.log.append({"time": watch_time(self.t), "text": text})
        self._say("世界", "你写下：%s %s" % (watch_time(self.t), text), kind="log")

    def _cross(self, line):
        try:
            index = int(line) - 1
        except (TypeError, ValueError):
            raise Refused("要划掉第几行？给一个行号。")
        if not 0 <= index < len(self.log):
            raise Refused("值班簿里没有第 %s 行。" % line)
        gone = self.log.pop(index)
        self._say("世界", "你划掉了「%s」。划掉的地方还看得见。" % gone["text"], kind="log")

    def _report_to_master(self):
        if self.place != "chart_room":
            raise Refused("你不在海图室。要报告，先下去。")
        if not self.sent_below:
            raise Refused("没有人叫你去。自己推门进去，是另一件事——这个模拟不许你做。")
        if self.reported_to_master:
            raise Refused("你已经报告过了。")
        self.reported_to_master = True
        self.place = "chart_room"
        self._say("世界", "你把 Stone 的话说了。船长没有坐起来。")
        self._say("船长", "Were they all white? Any colour in them at all?",
                  zh="「全是白的吗？里头有没有一点颜色？」", kind="master")
        self._say("世界", "「全是白的，先生。」你说。")
        self._say("船长", "What is the time?",
                  zh="「几点了？」", kind="master")
        self._say("世界", "「%s，先生。驾驶室的钟。」" % watch_time(self.t))
        self._say("世界", "他没有再说什么，也没有给你任何指示。他醒着。")

    # ---------------------------------------------------------------- the agent
    def _needs_stone(self, utterance):
        """Hand the utterance to the character.  Imported here so the world can
        be tested without a model or a network."""
        import stone
        return stone.respond(self, utterance)

    # ---------------------------------------------------------------- state
    def public(self):
        can_walk = [p for p in PLACES if p != self.place
                    and not (p == "chart_room" and not self.sent_below)]
        return {
            "clock": clock_text(self.t),
            "watch_time": watch_time(self.t),
            "place": self.place,
            "place_name": PLACES[self.place]["name"],
            "places": {k: v["name"] for k, v in PLACES.items()},
            "can_walk": can_walk,
            "objects": sorted(self.place_objects()),
            "strange": self.visible(),
            "rockets": self.rockets,
            "seen_rockets": self.seen_rockets,
            "sent_below": self.sent_below,
            "reported_to_master": self.reported_to_master,
            "log": self.log,
            "log_max": MAX_LOG,
            "stone": self.stone,
            "events": self.shown[-12:],
            "turns": self.turns,
            "calls": self.calls,
            "spend": self.spend,
            "refusals": self.refusals,
            "ended": self.ended,
            "divergence": self.divergence,
        }

    # ---------------------------------------------------------------- ending
    def ending(self):
        """What the court had, what the scrap log had, and what was lost."""
        fair = [entry for entry in self.log
                if re.search(r"\d|北|南|东|西|N\.|S\.|W\.|E\.|冰|风", entry["text"])]
        lost = [entry for entry in self.log if entry not in fair]
        return {
            "clock": clock_text(self.t),
            "scrap": list(self.log),
            "fair": fair,
            "lost": lost,
            "claims": list(self.claims),
            "reported": self.reported_to_master,
            "seen_rockets": self.seen_rockets,
            "rockets": self.rockets,
            "turns": self.turns,
            "divergence": self.divergence,
            "facts": {key: self.kb.get(key) for key in (
                "stone.rockets.five", "master.company", "master.morsing",
                "stone.send", "master.205", "stone.240", "stone.queer",
                "stone.fornothing", "beesley.rockets", "beesley.fishing",
                "court.rockets", "court.number", "court.ice", "court.saved",
                "court.distance", "court.night", "court.discrepancy",
            )},
        }
