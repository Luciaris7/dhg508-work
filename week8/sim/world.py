# Time costs, in minutes.  Bigger than life, so that a session is twenty turns
# and not two hundred.  (Invented: a choice of pace, marked in the parts table.)
COST = {
    "look": 5,
    "say": 4,
    "morse": 6,
    "walk": 6,
    "write": 2,
    "cross": 1,
    "wait": 10,
    "report": 3,
}

START = 15          # 00:15, when the session opens
END = 140           # 02:20, when the Titanic foundered
MAX_LOG = 8         # lines the scrap log will hold


def clock_text(minutes):
    total = START * 0 + minutes
    hour = (total // 60) % 24
    minute = total % 60
    return "%02d:%02d" % (hour, minute)


def watch_time(minutes):
    """The way it was written in a log: 12.20, 1.10, 2.5."""
    hour = minutes // 60
    hour12 = 12 if hour % 12 == 0 else hour % 12
    return "%d.%02d" % (hour12, minutes % 60)


WORDS = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
         "seven": 7, "eight": 8, "nine": 9, "ten": 10}
COUNT_WORDS = "|".join(WORDS)
COUNT_RE = re.compile(r"\b(\d{1,2}|%s)\b(?=\s*(?:white\s+)?rockets?\b)" % COUNT_WORDS,
                      re.IGNORECASE)
NOW_RE = re.compile(r"\b(\d{1,2}|%s)\b\s+now\b" % COUNT_WORDS, re.IGNORECASE)


def rocket_claim(text):
    """A number of rockets the player has just asserted, if any.

    The world does not accept a number because a person said it.  A wrong count
    is the sort of thing that went into the record too, so the sim keeps it: the
    claim is noted, the true count goes into the character's perception, and the
    ending shows both.
    """
    for pattern in (COUNT_RE, NOW_RE):
        match = pattern.search(text or "")
        if match:
            token = match.group(1).lower()
            return int(token) if token.isdigit() else WORDS[token]
    return None


