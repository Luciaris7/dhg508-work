"""The world: the Californian's bridge, the middle watch, 14-15 April 1912.

The rule of this file is the rule the assignment gives the character: **the
world, not the language model, decides what actually happens.**  A character
may say anything; what the ship does, what the clock does, what can be seen from
where, and what ends up in the log are decided here, in ordinary Python.

Nothing in this file is generated by a model.  Every event either comes from a
source (see data/californian_kb.json, which carries a locator for each fact) or
is marked in research/parts-table.md as inferred or invented.

Places, objects, rules, clock and the log are all in this one file on purpose:
138 lines of narrative logic that a reader can audit in a few minutes beats a
framework nobody can check.

Run the self-checks with:  python code/check_sim.py
"""

